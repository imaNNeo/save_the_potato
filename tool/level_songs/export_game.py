"""Exports the 10 level songs for the game:

- assets/audio/levels/NN/stem_{drums,keys,hats16,arp}.ogg, one backing loop each
  (8 bars, or the whole tune for levels 1-6)
- lib/presentation/rhythm/level_songs.dart, the melody phrases and the form

  python3 tool/level_songs/export_game.py [--only 1,2]   (from the repo root; needs numpy,
  scipy, soundfile and ffmpeg)

The melodies of levels 7-10 come from songs.py with fixed seeds, and levels
1-6 are written out in classical.py, so running it again gives the same songs.
"""
import os, subprocess, sys

sys.path.insert(0, os.path.dirname(__file__))
import numpy as np
import soundfile as sf
from songs import SONGS, INTRO_BARS, level_ending, finale, design, stems, chord_pcs, song_form, stages_of, is_full, n_bars, beats_of, chords_of_bar
import synth

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
ASSETS = os.path.join(ROOT, 'assets', 'audio', 'levels')
DART = os.path.join(ROOT, 'lib', 'presentation', 'rhythm', 'level_songs.dart')

# The same loudness as the infinite song's stems
TARGET_RMS = 10 ** (-18.6 / 20)
GROUPS = {
    'drums': ['kick', 'claps', 'hats'],
    'keys': ['pad', 'bass'],
    'hats16': ['hats16'],
    'arp': ['arp'],
}


def write_ogg(st, path):
    w = path[:-4] + '.wav'
    sf.write(w, st.T, synth.SR)
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', w, '-c:a', 'libvorbis', '-q:a', '2', path], check=True)
    os.remove(w)


def dart_phrase(var, p):
    notes = ',\n'.join(f'      MelodyNote({n[0]}, {n[1]:g}, {n[2]}' + (f', {str(n[3]).lower()}' if len(n) > 3 else '') + ')'
                        for n in p['notes'])
    return f"""  static const {var} = MelodyPhrase(
    '{p['name']}',
    iceFrom: {p['iceFrom']},
    notes: [
{notes},
    ],
  );
"""


def main(only=None):
    out = ['// Generated by tool/level_songs/export_game.py. Do not edit by hand.',
           '// ignore_for_file: lines_longer_than_80_chars', '',
           "import 'rhythm_songs.dart';", '',
           '/// The 10 songs of the levels mode, one per level. Each one is a',
           '/// [Song] that plays its form once, about 2 minutes, and the level',
           '/// is cleared when it ends.',
           'class LevelSongs {', '  LevelSongs._();', '']
    songs_list = []
    for song in SONGS:
        lv = song['level']
        phrases = design(song)
        if only is None or lv in only:
            st = stems(song)
            full = sum(st.values())
            g = TARGET_RMS / np.sqrt((full ** 2).mean())
            d = os.path.join(ASSETS, f'{lv:02d}')
            os.makedirs(d, exist_ok=True)
            for name, parts in GROUPS.items():
                write_ogg(sum(st[p] for p in parts) * g, os.path.join(d, f'stem_{name}.ogg'))
            print('level', lv, song['name'], 'stems written', flush=True)
        tonic = synth.NOTE[song['tonic']]
        chords = ', '.join('[' + ', '.join(str(x) for x in chord_pcs(tonic, chords_of_bar(song, b)[0][1])) + ']'
                           for b in range(n_bars(song) if is_full(song) else len(song['chords'])))
        cls = f'_Level{lv}'
        for kind in phrases:
            out.append(dart_phrase(f'_l{lv}{kind.capitalize()}', phrases[kind]))
        stages = []
        for frm, names, layers in stages_of(song):
            ps = ', '.join(f'_l{lv}{n.capitalize()}' for n in names)
            ls = ', '.join(f"'{x}'" for x in layers)
            stages.append(f'      SongStage(from: {frm}, phrases: [{ps}], layers: [{ls}]),')
        form = ', '.join(f'SongSection.{s}' for s in song_form(song))
        name = song['name'].replace("'", "\\'")
        c = song['colors']
        extra = (f"\n      bars: {n_bars(song)},\n      beatsPerBar: {beats_of(song)},\n      fullMelody: true," if is_full(song) else '')
        pickup_from, ends_at = level_ending(song)
        extra += f"\n      introBars: {INTRO_BARS},"
        if pickup_from is not None:
            extra += f"\n      pickupFrom: {pickup_from:g},"
        extra += f"\n      endsAt: {ends_at:g},"
        extra += f"\n      finale: [{', '.join(str(x) for x in finale(song))}],"
        songs_list.append(f"""    Song(
      id: 'level{lv}',
      name: '{name}',
      bpm: {song['bpm']},
      assetDir: 'levels/{lv:02d}',
      stems: ['drums', 'keys'],
      drumStems: ['drums'],
      endless: false,
      chords: [{chords}],
      colors: [{', '.join('0xFF' + x[1:].upper() for x in c)}],
      stages: [
{chr(10).join(stages)}
      ],
      form: [{form}],{extra}
    ),""")
    out.append('  static const all = [')
    out.extend(songs_list)
    out.append('  ];')
    out.append('}')
    open(DART, 'w').write('\n'.join(out) + '\n')
    print('wrote', DART)


if __name__ == '__main__':
    # --only 1,2 writes the stems of those levels only (the Dart file always
    # has every level)
    only = None
    if '--only' in sys.argv:
        only = [int(x) for x in sys.argv[sys.argv.index('--only') + 1].split(',')]
    main(only)
